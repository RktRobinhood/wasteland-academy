#!/usr/bin/env node
// ── GAME MOVES COPY ──────────────────────────────────────────
// The Godot game can't read files outside game/, so it gets a generated copy of the
// explainer moves (FAL-429): from curriculum/moves.json each move's name and the line
// Spark says for it, and curriculum/moves-map.json's step map and branches as they are.
// The engine tags every worked step from it at runtime (game/engine/moves.gd).
//
//   node tools/game-moves.mjs           print whether the copy is current
//   node tools/game-moves.mjs --write   rewrite game/data/moves.json
//
// The curriculum files stay the single source. tests/unit/game-moves.test.mjs fails
// when the copy is stale.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'game/data/moves.json');
const readJSON = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

export function build() {
  const moves = readJSON('curriculum/moves.json');
  const map = readJSON('curriculum/moves-map.json');
  const out = {
    about: 'Generated by tools/game-moves.mjs from curriculum/moves.json and moves-map.json. Do not edit.',
    moves: {},
    map: map.map,
    branches: map.branches ?? [],
  };
  for (const m of moves.moves) if (!m.retired) out.moves[m.id] = { name: m.name, say: m.say };
  return JSON.stringify(out, null, 1) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = build();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--write')) {
    fs.writeFileSync(OUT, text);
    console.log(`Wrote ${path.relative(ROOT, OUT)}.`);
  } else {
    console.log(current === text ? 'game/data/moves.json is current.' : 'game/data/moves.json is stale: run with --write.');
    if (current !== text) process.exit(1);
  }
}
