#!/usr/bin/env node
// ── GAME CATALOGUE COPY ──────────────────────────────────────
// The Godot game can't read files outside game/, so it gets a generated copy of the
// parts of curriculum/question-types.json the question engine plans from: the
// situations, regions, levels and topic names, and every type with its views (the
// explorer screen shows the types not built yet too). Method
// names and summaries are filled in from curriculum/aa-sl.json, aa-hl.json and ai.json, so a worked solution
// can name its method, and the name of every skill an unknown lists, so the map can
// name a player's weakest skills.
//
//   node tools/game-catalogue.mjs           print what would change
//   node tools/game-catalogue.mjs --write   rewrite game/data/catalogue.json
//
// question-types.json stays the single source. tests/unit/game-catalogue.test.mjs
// fails when the copy is stale.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'game/data/catalogue.json');
const readJSON = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

// Fields of a type the engine reads. Bank part lists and exam prose stay behind.
const TYPE_FIELDS = ['id', 'topic', 'source', 'kind', 'region', 'name', 'summary', 'situation', 'level',
  'formats', 'representations', 'unknowns', 'angles', 'concepts', 'misconceptions', 'methods', 'chain', 'supports'];

// The game's default font has superscript digits but no superscript letters (FAL-499),
// so a power with a letter in it is written with a caret, as the engine writes it:
// eˣ -> e^x, b²ˣ -> b^(2x), x⁻ⁿ -> x^(−n). Powers of digits only (x², 2⁻¹) stay.
const SUP_LETTERS = 'ᵃaᵇbᶜcᵈdᵉeᶠfᵍgʰhⁱiʲjᵏkˡlᵐmⁿnᵒoᵖpʳrˢsᵗtᵘuᵛvʷwˣxʸyᶻz';
const SUP_OTHERS = '⁰0¹1²2³3⁴4⁵5⁶6⁷7⁸8⁹9⁻−⁺+';
const SUP = new Map();
for (const s of [SUP_LETTERS, SUP_OTHERS]) for (let i = 0; i < s.length; i += 2) SUP.set(s[i], s[i + 1]);
const SUP_RUN = new RegExp(`[${[...SUP.keys()].join('')}]+`, 'g');
const LETTER = new RegExp(`[${[...SUP_LETTERS].filter((_, i) => i % 2 === 0).join('')}]`);

export function caretPowers(text) {
  return text.replace(SUP_RUN, run => {
    if (!LETTER.test(run)) return run;
    const plain = [...run].map(c => SUP.get(c)).join('');
    return plain.length === 1 ? `^${plain}` : `^(${plain})`;
  });
}

export function build() {
  const doc = readJSON('curriculum/question-types.json');
  const map = readJSON('curriculum/aa-sl.json');
  // Names and methods come from every layer, so a type built for AA HL or AI skills reads like the rest.
  const skills = new Map();
  for (const layer of ['aa-sl', 'aa-hl', 'ai'])
    for (const t of readJSON(`curriculum/${layer}.json`).topics) for (const st of t.subtopics) for (const s of st.skills) skills.set(s.id, s);
  const types = doc.types.map(t => {
    const out = {};
    for (const f of TYPE_FIELDS) if (t[f] !== undefined) out[f] = t[f];
    // How often the IB asks this type: the planner's third rule and the exam-only mix.
    out.frequency = t.stats?.parts ?? 0;
    // Marks a typical exam part of this type is worth: the timer's base (Q6 on FAL-274).
    if (t.stats?.marks?.median !== undefined) out.marks = t.stats.marks.median;
    // Section A and B bank parts: a boss (G4) favours the types Section B chains most.
    if (t.stats?.section) out.section = t.stats.section;
    // How often the IB asked the type on each paper: the game makes Paper 1 and Paper 2
    // versions in that ratio (FAL-419).
    if (t.stats?.paper) out.paper = t.stats.paper;
    out.angles = (t.angles || []).map(a => {
      const m = a.skill ? skills.get(a.skill)?.methods.find(x => x.id === a.method) : t.methods?.find(x => x.id === a.method);
      return { ...a, name: m?.name ?? a.method, about: m?.summary ?? '' };
    });
    out.misconceptions = (t.misconceptions || []).map(m => ({ ...m }));
    return out;
  });
  // Skill id -> its name, for every skill an unknown lists (the map's weakest skills).
  const skillNames = {};
  for (const t of types) for (const u of t.unknowns || []) for (const id of u.skills || []) {
    if (!(id in skillNames)) skillNames[id] = skills.get(id)?.name ?? id;
  }
  const json = { about: 'Generated by node tools/game-catalogue.mjs --write from curriculum/question-types.json and curriculum/aa-sl.json. Do not edit.',
    levels: doc.levels, topics: map.topics.map(t => ({ n: t.topic, name: t.name })),
    regions: doc.regions, situations: doc.situations, skills: skillNames, types };
  return caretPowers(JSON.stringify(json, null, '\t')) + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = build();
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${next.length} bytes)`);
  } else {
    console.log(now === next ? 'game/data/catalogue.json is up to date' : 'game/data/catalogue.json is stale: run node tools/game-catalogue.mjs --write');
    process.exit(now === next ? 0 : 1);
  }
}
